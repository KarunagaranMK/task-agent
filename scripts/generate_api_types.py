"""Generate TypeScript API contracts from the FastAPI OpenAPI schema."""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))


def ts_type(schema: dict[str, Any] | bool | None) -> str:
    if schema is None or schema is True:
        return "unknown"
    if schema is False:
        return "never"
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return f"components['schemas'][{json.dumps(name)}]"
    if "const" in schema:
        base = json.dumps(schema["const"])
        return base
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"]) or "never"
    if "oneOf" in schema or "anyOf" in schema:
        variants = schema.get("oneOf", schema.get("anyOf", []))
        result = " | ".join(f"({ts_type(item)})" for item in variants) or "never"
    elif "allOf" in schema:
        result = " & ".join(f"({ts_type(item)})" for item in schema["allOf"]) or "unknown"
    elif schema.get("type") == "array":
        result = f"Array<{ts_type(schema.get('items'))}>"
    elif schema.get("type") == "object" or "properties" in schema or "additionalProperties" in schema:
        properties = schema.get("properties", {})
        required = set(schema.get("required", []))
        entries = [
            f"{json.dumps(name)}{'?' if name not in required else ''}: {ts_type(value)}"
            for name, value in properties.items()
        ]
        extra = schema.get("additionalProperties")
        if extra is not None and extra is not False:
            entries.append(f"[key: string]: {ts_type(extra)}")
        result = "{ " + "; ".join(entries) + ("; " if entries else "") + "}"
    else:
        result = {
            "string": "string",
            "integer": "number",
            "number": "number",
            "boolean": "boolean",
            "null": "null",
        }.get(schema.get("type"), "unknown")
    return f"{result} | null" if schema.get("nullable") else result


def content_type(content: dict[str, Any]) -> str:
    variants = [
        f"{json.dumps(media_type)}: {ts_type(media.get('schema'))}"
        for media_type, media in content.items()
    ]
    return "{ " + "; ".join(variants) + ("; " if variants else "") + "}"


def generate() -> str:
    from app.main import app

    document = app.openapi()
    schemas = document.get("components", {}).get("schemas", {})
    lines = [
        "/* Generated by scripts/generate_api_types.py. Do not edit by hand. */",
        "export interface components {",
        "  schemas: {",
    ]
    for name, schema in schemas.items():
        lines.append(f"    {json.dumps(name)}: {ts_type(schema)}")
    lines.extend(["  }", "}", "", "export interface paths {"])

    for path, path_item in document.get("paths", {}).items():
        methods = [(method, operation) for method, operation in path_item.items() if method.lower() in {
            "get", "post", "put", "patch", "delete", "options", "head", "trace"
        }]
        if not methods:
            continue
        lines.append(f"  {json.dumps(path)}: {{")
        for method, operation in methods:
            lines.append(f"    {method.lower()}: {{")
            if operation.get("operationId"):
                lines.append(f"      operationId: {json.dumps(operation['operationId'])}")
            parameters = operation.get("parameters", [])
            if parameters:
                required = [p for p in parameters if p.get("required")]
                optional = [p for p in parameters if not p.get("required")]
                lines.append("      parameters: {")
                for group, items in (("path", [p for p in required if p.get("in") == "path"]),
                                     ("query", [p for p in parameters if p.get("in") == "query"]),
                                     ("header", [p for p in parameters if p.get("in") == "header"])):
                    if items:
                        lines.append(f"        {group}: {{ " + "; ".join(
                            f"{json.dumps(p['name'])}{'' if p.get('required') else '?'}: {ts_type(p.get('schema'))}"
                            for p in items
                        ) + " }")
                if optional:
                    lines.append("        __optional: true")
                lines.append("      }")
            request = operation.get("requestBody")
            if request:
                lines.append("      requestBody: {")
                lines.append(f"        required: {str(bool(request.get('required'))).lower()}")
                lines.append(f"        content: {content_type(request.get('content', {}))}")
                lines.append("      }")
            lines.append("      responses: {")
            for status_code, response in operation.get("responses", {}).items():
                lines.append(f"        {json.dumps(status_code)}: {{")
                if response.get("content"):
                    lines.append(f"          content: {content_type(response['content'])}")
                else:
                    lines.append("          content?: never")
                lines.append("        }")
            lines.extend(["      }", "    }"])
        lines.append("  }")
    lines.extend(["}", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    destination = ROOT / "frontend" / "src" / "api" / "generated.ts"
    destination.write_text(generate(), encoding="utf-8")
    print(f"Generated {destination.relative_to(ROOT)}")
